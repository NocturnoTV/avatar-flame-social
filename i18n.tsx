export const LANGUAGE_LOCALES: Record<LangCode, string> = {
  fr: "fr-FR",
  en: "en-US",
  es: "es-ES",
  pt: "pt-BR",
  de: "de-DE",
  ko: "ko-KR",
};

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  locale: string;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("fr");

  useEffect(() => {
    const stored = window.localStorage.getItem("bloxspark-lang") as LangCode | null;
    if (stored && stored in DICTS) setLangState(stored);
    else {
      const nav = window.navigator.language.slice(0, 2) as LangCode;
      if (nav in DICTS) setLangState(nav);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nValue>(() => {
    const setLang = (l: LangCode) => {
      setLangState(l);
      window.localStorage.setItem("bloxspark-lang", l);
    };
    const t = (key: string, vars?: Record<string, string | number>) => {
      let str = EXTRA[lang]?.[key] ?? DICTS[lang]?.[key] ?? EXTRA.en[key] ?? en[key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
      }
      return str;
    };
    return { lang, locale: LANGUAGE_LOCALES[lang], setLang, t };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
