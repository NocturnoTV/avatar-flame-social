const DICTS: Record<LangCode, Dict> = { en, fr, es, pt, de, ko };

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: keyof typeof en, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("fr");

  useEffect(() => {
    const stored = window.localStorage.getItem("bloxspark-lang") as LangCode | null;
    if (stored && stored in DICTS) setLangState(stored);
    else {
      const nav = window.navigator.language.slice(0, 2) as LangCode;
      if (nav in DICTS) setLangState(nav);
    }
  }, []);

  const value = useMemo<I18nValue>(() => {
    const setLang = (l: LangCode) => {
      setLangState(l);
      window.localStorage.setItem("bloxspark-lang", l);
    };
    const t = (key: keyof typeof en, vars?: Record<string, string | number>) => {
      let str = DICTS[lang]?.[key] ?? en[key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
      }
      return str;
    };
    return { lang, setLang, t };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
